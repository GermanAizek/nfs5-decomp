    print("RUNNING MATCHED FUNCTIONS VERIFICATION SUITE")
    print("=" * 70)

    passed = 0
    total = len(MATCHED_FUNCTIONS)

    with tempfile.TemporaryDirectory() as tmpdir:
        for idx, (va, sz, asm) in enumerate(MATCHED_FUNCTIONS, 1):
            s_file = os.path.join(tmpdir, f"fn_{idx}.s")
            o_file = os.path.join(tmpdir, f"fn_{idx}.o")
            bin_file = os.path.join(tmpdir, f"fn_{idx}.bin")

            with open(s_file, "w") as f:
                f.write(asm)

            subprocess.run(["i686-w64-mingw32-as", s_file, "-o", o_file], check=True)
            subprocess.run(["objcopy", "-O", "binary", "-j", ".text", o_file, bin_file], check=True)

            with open(bin_file, "rb") as f:
                cand_bytes = f.read()[:sz]

            ok = vf.verify_function(va, candidate_bytes=cand_bytes)
            if ok:
                passed += 1
            else:
                print(f"FAILED: {va}")

    print("\n" + "=" * 70)
    print(f"VERIFICATION SUMMARY: {passed}/{total} functions 100% BIT-PERFECT MATCH")
    print("=" * 70)
    assert passed == total, f"Only {passed}/{total} functions passed!"
    return passed == total

